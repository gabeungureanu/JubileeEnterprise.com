class CostFirstClassifier:
    """
    Main cost-first classifier that orchestrates the classification pipeline.

    This is the primary interface for cheap-first routing. It:
    1. ALWAYS attempts zero-token classification first
    2. Only invokes LLM if confidence is insufficient
    3. Tracks cost metrics and savings

    USAGE:
        classifier = CostFirstClassifier()
        result = classifier.classify("What is the meaning of John 3:16?")
        tier = result.classification.intent  # Use for routing
    """

    def __init__(
        self,
        zero_token_config: ZeroTokenConfig = None,
        minimal_llm_config: MinimalClassifierConfig = None,
        call_llm: Callable = None,
        confidence_threshold: float = 0.70,
    ):
        """
        Initialize the cost-first classifier.

        Args:
            zero_token_config: Config for zero-token classifier
            minimal_llm_config: Config for minimal LLM classifier
            call_llm: Function to call LLM (if needed)
            confidence_threshold: Threshold for skipping LLM
        """
        self.zero_token = ZeroTokenClassifier(zero_token_config)
        self.minimal_llm = MinimalLLMClassifier(minimal_llm_config, call_llm)
        self.confidence_threshold = confidence_threshold

        # Statistics
        self._stats = {
            "total_classifications": 0,
            "zero_token_successes": 0,
            "llm_invocations": 0,
            "total_tokens_used": 0,
            "estimated_savings": 0.0,
        }

    def classify(
        self,
        message: str,
        context: Dict[str, Any] = None,
    ) -> CheapClassificationResult:
        """
        Classify a message using cost-first strategy.

        Args:
            message: The user's message
            context: Optional context

        Returns:
            CheapClassificationResult
        """
        self._stats["total_classifications"] += 1

        # Step 1: ALWAYS try zero-token first
        result, is_confident = self.zero_token.classify(message, context)

        if is_confident or result.final_confidence >= self.confidence_threshold:
            # Zero-token succeeded - no LLM needed
            self._stats["zero_token_successes"] += 1
            result.estimated_cost_saved = self._estimate_savings()
            return result

        # Step 2: Zero-token insufficient - invoke minimal LLM
        logger.info(
            f"Zero-token confidence {result.final_confidence:.2f} below threshold "
            f"{self.confidence_threshold:.2f}, invoking minimal LLM"
        )

        result = self.minimal_llm.classify(message, result)
        self._stats["llm_invocations"] += 1
        self._stats["total_tokens_used"] += result.tokens_used

        return result

    def _estimate_savings(self) -> float:
        """Estimate cost saved by using zero-token classification."""
        # Rough estimate: LLM classification costs ~50 tokens
        # If we skip LLM, we save those tokens
        return 50 * 0.00001  # Rough cost per token

    def get_statistics(self) -> Dict[str, Any]:
        """Get classification statistics."""
        stats = self._stats.copy()
        if stats["total_classifications"] > 0:
            stats["zero_token_rate"] = (
                stats["zero_token_successes"] / stats["total_classifications"]
            )
            stats["llm_invocation_rate"] = (
                stats["llm_invocations"] / stats["total_classifications"]
            )
        return stats

    def reset_statistics(self):
        """Reset classification statistics."""
        self._stats = {
            "total_classifications": 0,
            "zero_token_successes": 0,
            "llm_invocations": 0,
            "total_tokens_used": 0,
            "estimated_savings": 0.0,
        }


