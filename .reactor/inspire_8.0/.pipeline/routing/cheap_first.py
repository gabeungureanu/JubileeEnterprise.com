# The minimal classifier prompt - as short as possible
MINIMAL_CLASSIFIER_PROMPT = """Classify intent: R=routine, T=teaching, D=doctrine, C=crisis
Message: {message}
Output format: INTENT:X (X is one letter)"""

# Maximum tokens for classifier response
CLASSIFIER_MAX_TOKENS = 10


@dataclass
class MinimalClassifierConfig:
    """Configuration for minimal LLM classifier."""

    # Model to use (always the cheapest)
    model_id: str = "gpt-4o-mini"

    # Prompt configuration
    prompt_template: str = MINIMAL_CLASSIFIER_PROMPT
    max_tokens: int = CLASSIFIER_MAX_TOKENS

    # Response parsing
    valid_responses: List[str] = field(
        default_factory=lambda: ["R", "T", "D", "C"]
    )

    # Timeouts
    timeout_seconds: float = 5.0


class MinimalLLMClassifier:
    """
    Minimal LLM classifier for ambiguous cases.

    This classifier is ONLY invoked when zero-token classification
    fails to achieve sufficient confidence. It uses:
    - The cheapest available model
    - A minimal, tightly constrained prompt
    - Fixed, machine-readable output format
    - NO user-facing text generation

    CRITICAL: This should be invoked as rarely as possible.
    """

    # Intent mapping from classifier response
    INTENT_MAP = {
        "R": IntentCategory.ROUTINE_REQUEST,
        "T": IntentCategory.TEACHING_REQUEST,
        "D": IntentCategory.DOCTRINAL_QUESTION,
        "C": IntentCategory.CRISIS_GUIDANCE,
    }

    # Tier mapping from classifier response
    TIER_MAP = {
        "R": ModelTier.ECONOMY,
        "T": ModelTier.STANDARD,
        "D": ModelTier.PREMIUM,
        "C": ModelTier.PREMIUM,
    }

    # Risk mapping from classifier response
    RISK_MAP = {
        "R": RiskLevel.LOW,
        "T": RiskLevel.MEDIUM,
        "D": RiskLevel.HIGH,
        "C": RiskLevel.CRITICAL,
    }

    def __init__(
        self,
        config: MinimalClassifierConfig = None,
        call_llm: Callable = None,
    ):
        """
        Initialize the minimal classifier.

        Args:
            config: Classifier configuration
            call_llm: Function to call the LLM (message, model_id, max_tokens) -> response
        """
        self.config = config or MinimalClassifierConfig()
        self.call_llm = call_llm

    def classify(
        self,
        message: str,
        partial_result: CheapClassificationResult = None,
    ) -> CheapClassificationResult:
        """
        Classify using minimal LLM prompt.

        Args:
            message: The user's message
            partial_result: Partial result from zero-token classification

        Returns:
            CheapClassificationResult with LLM classification
        """
        start_time = datetime.now()

        # Initialize or update result
        if partial_result:
            result = partial_result
        else:
            result = CheapClassificationResult(
                classification=ClassificationResult(message_length=len(message))
            )

        result.llm_invoked = True
        result.source = ClassificationSource.MINIMAL_LLM

        # Check if we have a call_llm function
        if not self.call_llm:
            logger.warning("No call_llm function provided, using fallback")
            result.escalation_reason = "No LLM function available"
            self._apply_fallback(result)
            self._finalize_timing(result, start_time)
            return result

        try:
            # Build the minimal prompt
            prompt = self.config.prompt_template.format(
                message=message[:200]  # Truncate for cost
            )

            # Call the LLM
            response = self.call_llm(
                prompt,
                self.config.model_id,
                self.config.max_tokens,
            )

            # Parse the response
            intent_code = self._parse_response(response)

            if intent_code and intent_code in self.INTENT_MAP:
                # Successful classification
                result.classification.intent = self.INTENT_MAP[intent_code]
                result.classification.risk = self.RISK_MAP[intent_code]
                result.classification.complexity = (
                    ComplexityLevel.LOW if intent_code == "R"
                    else ComplexityLevel.MEDIUM if intent_code == "T"
                    else ComplexityLevel.HIGH
                )
                result.classification.intent_confidence = 0.80
                result.final_confidence = 0.80
                result.tier_justification = f"LLM classified as '{intent_code}'"

                # Estimate tokens used
                result.tokens_used = len(prompt.split()) + 5  # Rough estimate
            else:
                # Failed to parse response
                logger.warning(f"Failed to parse LLM response: {response}")
                result.escalation_reason = f"Failed to parse LLM response: {response}"
                self._apply_fallback(result)

        except Exception as e:
            logger.error(f"LLM classification failed: {e}")
            result.escalation_reason = f"LLM error: {str(e)}"
            self._apply_fallback(result)

        self._finalize_timing(result, start_time)
        return result

    def _parse_response(self, response: str) -> Optional[str]:
        """Parse the LLM response to extract intent code."""
        if not response:
            return None

        # Look for pattern INTENT:X
        import re
        match = re.search(r"INTENT:([RTDC])", response.upper())
        if match:
            return match.group(1)

        # Fallback: look for single letter
        response_clean = response.strip().upper()
        if len(response_clean) == 1 and response_clean in "RTDC":
            return response_clean

        return None

    def _apply_fallback(self, result: CheapClassificationResult):
        """Apply fallback classification when LLM fails."""
        # Default to standard tier for safety
        result.classification.intent = IntentCategory.UNKNOWN
        result.classification.risk = RiskLevel.MEDIUM
        result.classification.complexity = ComplexityLevel.MEDIUM
        result.classification.intent_confidence = 0.50
        result.final_confidence = 0.50
        result.tier_justification = "Fallback to standard tier (LLM failed)"

    def _finalize_timing(self, result: CheapClassificationResult, start_time: datetime):
        """Finalize timing information."""
        end_time = datetime.now()
        llm_time = (end_time - start_time).total_seconds() * 1000
        result.classification_time_ms += llm_time
        result.classified_at = end_time.isoformat()


